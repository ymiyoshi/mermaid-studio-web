export type MessageKey = keyof typeof ja;

export function t(key: MessageKey, params?: Record<string, string>): string {
  let s: string = ja[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
